// Generates the themed twin of every stylesheet. Run after editing a stylesheet: node tools/build-theme-css.mjs
// (a test fails when a twin is out of date).
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const Theme=createRequire(import.meta.url)('../desktop/ui/theme.js');
export const SHEETS=['app','library','models'];
export async function render(name){
  const source=await readFile(new URL(`../desktop/ui/${name}.css`,import.meta.url),'utf8');
  return `/* Generated by tools/build-theme-css.mjs from ${name}.css — do not edit. */\n`+Theme.recolorCss(source);
}
if(import.meta.url===`file://${process.argv[1]}`){
  for(const name of SHEETS){await writeFile(new URL(`../desktop/ui/${name}.themed.css`,import.meta.url),await render(name));console.log('written',name+'.themed.css');}
}
